"""Generate docs/PYTHON-CODEMAP.md: a line-numbered index of the Python app.

reference/python/app.py (the frozen Python version, the spec for the .NET
port) is a single ~6,300-line module, so the fastest way to find anything is
a table of its sections, top-level symbols and class methods with line
numbers. It is stdlib-only and works on Windows and Linux.

    python tools/codemap.py            # writes docs/PYTHON-CODEMAP.md
    python tools/codemap.py --check    # exit 1 if PYTHON-CODEMAP.md is stale
"""

import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "reference" / "python" / "app.py"
OUTPUT = ROOT / "docs" / "PYTHON-CODEMAP.md"

# Section banners in app.py are Italian; show an English name next to them.
SECTION_NAMES = {
    "CONFIGURAZIONE": "Configuration",
    "MONITOR SETUP": "Monitor profiles (MonitorSwitcher)",
    "MAPPA TASTO HOME": "Home key remapping",
    "CONTROLLER": "Gamepad input and combos",
    "MEDIA IN RIPRODUZIONE": "Now playing (Windows media session)",
    "USCITA AUDIO": "Audio output (SteelSeries Sonar / Windows)",
    "LIBRERIA GIOCHI": "Steam game library",
    "VOLUME, BATTERIA DEL PAD, ALIMENTAZIONE": "Volume, pad battery, power",
    "SPOTIFY": "Spotify Web API",
    "DISCORD": "Discord local RPC",
    "OVERLAY GAMEPAD": "Overlay window (Tk + Pillow)",
    "AVVIO CON WINDOWS": "Start with Windows (scheduled task)",
    "TRAY ICON / MENU": "Tray icon and menu",
}

BANNER = re.compile(r"^# -{20,}\s*$")


def find_sections(lines):
    """Return [(line_no, title)] for '# ----' / '# TITLE' / '# ----' banners."""
    sections = []
    for i in range(len(lines) - 2):
        if BANNER.match(lines[i]) and BANNER.match(lines[i + 2]):
            title = lines[i + 1].lstrip("#").strip()
            if title:
                sections.append((i + 2, title))  # 1-based line of the title
    return sections


def english(title):
    for key, name in SECTION_NAMES.items():
        if title.upper().startswith(key):
            return name
    return ""


def first_line(doc):
    return doc.strip().splitlines()[0] if doc else ""


def collect(tree):
    """Top-level functions, classes (with methods) and UPPER_CASE constants."""
    items = []
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            items.append(("def", node.name, node.lineno, node.end_lineno, []))
        elif isinstance(node, ast.ClassDef):
            methods = [(m.name, m.lineno, m.end_lineno) for m in node.body
                       if isinstance(m, (ast.FunctionDef, ast.AsyncFunctionDef))]
            items.append(("class", node.name, node.lineno, node.end_lineno, methods))
        elif isinstance(node, (ast.Assign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            for t in targets:
                if isinstance(t, ast.Name) and t.id.isupper() and len(t.id) > 2:
                    items.append(("const", t.id, node.lineno, node.end_lineno, []))
    return items


def render():
    text = SOURCE.read_text(encoding="utf-8")
    lines = text.splitlines()
    tree = ast.parse(text)
    sections = find_sections(lines)
    items = collect(tree)

    def section_of(line):
        current = None
        for start, title in sections:
            if start <= line:
                current = (start, title)
        return current

    out = [
        "# Python app.py code map",
        "",
        "Generated by `python tools/codemap.py` - do not edit by hand.",
        f"Source: `reference/python/app.py`, {len(lines)} lines, {len(sections)} sections.",
        "Line numbers are 1-based. Section names are the Italian banners in the code.",
        "",
        "## Sections",
        "",
        "| Line | Section (as in code) | English | Ends |",
        "|---:|---|---|---:|",
    ]
    bounds = [s for s, _ in sections] + [len(lines) + 2]
    for (start, title), nxt in zip(sections, bounds[1:]):
        out.append(f"| {start} | `{title}` | {english(title)} | {nxt - 2} |")
    out.append("")

    grouped = {}
    for item in items:
        key = section_of(item[2])
        grouped.setdefault(key, []).append(item)

    order = [None] + sections
    for key in order:
        group = grouped.get(key)
        if not group:
            continue
        heading = "Module header (imports, feature flags)" if key is None else \
            f"{key[1]} - {english(key[1])}".rstrip(" -")
        out += [f"## {heading}", ""]
        consts = [g for g in group if g[0] == "const"]
        if consts:
            out.append("Constants: " + ", ".join(f"`{c[1]}` ({c[2]})" for c in consts))
            out.append("")
        for kind, name, start, end, methods in group:
            if kind == "const":
                continue
            label = "class " if kind == "class" else ""
            out.append(f"- `{label}{name}` - {start}-{end}")
            if kind == "class" and methods:
                for m, ms, me in methods:
                    out.append(f"  - `.{m}` - {ms}-{me}")
        out.append("")
    return "\n".join(out)


def main():
    content = render()
    if "--check" in sys.argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != content:
            print("docs/PYTHON-CODEMAP.md is stale: run python tools/codemap.py")
            sys.exit(1)
        print("docs/PYTHON-CODEMAP.md is up to date")
        return
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content, encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
